import streamlit as st
import pandas as pd
from ui import page_intro, card

page_intro("01 / CONCEPT", "데이터에서 규칙을 배우는 방법", "머신러닝의 핵심을 이해하고, 사례를 살펴본 뒤 나만의 붓꽃 분류 실험으로 연결해 보세요.")
st.markdown('''## 머신러닝이란?
**머신러닝(Machine Learning)**은 사람이 모든 판단 규칙을 직접 작성하는 대신,
컴퓨터가 **데이터에서 패턴을 학습해 새로운 입력을 예측하거나 분류**하게 하는 인공지능 기술입니다.
학습한 결과물은 **모델**이라고 부릅니다. 모델은 데이터에 담긴 경향을 이용하므로 틀릴 수도 있습니다.
''')
a, b = st.columns(2)
with a:
    card("RULE-BASED", "규칙을 사람이 작성", "예: ‘꽃잎 길이가 특정 값보다 짧으면 A종’이라는 조건을 사람이 정합니다. 데이터가 달라지면 조건도 다시 검토해야 합니다.")
with b:
    card("MACHINE LEARNING", "사례를 보고 규칙 학습", "이미 종을 알고 있는 꽃들의 측정값을 모델에 보여 줍니다. 모델은 값과 종 사이의 패턴을 찾아 새로운 꽃을 분류합니다.")
st.markdown("## 꼭 알아둘 네 가지 말")
st.table(pd.DataFrame([
    ["데이터", "학습과 평가에 사용하는 사례", "붓꽃 150개체의 측정 기록"],
    ["특징 변수 · X", "모델에 넣는 관찰값", "꽃받침 길이·너비, 꽃잎 길이·너비"],
    ["정답 · y", "학습할 때 알려 주는 목표 값", "setosa / versicolor / virginica"],
    ["예측", "학습한 모델이 새 입력에 내리는 판단", "네 측정값을 보고 붓꽃의 종 분류"],
], columns=["용어", "의미", "붓꽃 예시"]))
st.markdown("## 학습 방식은 어떻게 다를까요?")
t1, t2, t3 = st.tabs(["지도학습", "비지도학습", "강화학습"])
with t1:
    st.markdown('''### 정답이 있는 사례로 학습
입력과 정답의 관계를 배웁니다. **분류**는 종·스팸 여부 같은 범주를, **회귀**는 가격·전력 사용량 같은 수치를 예측합니다.

**이번 실험:** 붓꽃의 네 특징과 종 이름으로 SVM 분류기를 학습합니다.''')
with t2:
    st.markdown('''### 정답 없이 데이터의 구조 탐색
비슷한 데이터끼리 묶는 **군집화**, 복잡한 특징을 줄여 보는 **차원 축소** 등이 있습니다.

**예:** 비슷한 독서 성향을 가진 이용자 집단 찾기. 집단 이름과 의미는 사람이 추가로 해석해야 합니다.''')
with t3:
    st.markdown('''### 행동의 결과와 보상으로 학습
에이전트가 환경에서 행동하고 보상을 받아, 장기적으로 더 나은 결과를 얻는 정책을 배웁니다.

**예:** 시뮬레이션에서 로봇이 넘어지지 않고 이동하는 전략 학습. 지도학습의 정답 맞히기와는 구조가 다릅니다.''')
st.markdown('''## 데이터에서 예측까지
1. **문제 정하기:** 무엇을 예측할지 정합니다.
2. **데이터 준비:** 특징과 정답을 확인하고 측정 오류를 점검합니다.
3. **학습·평가 분리:** 모델이 보지 못한 데이터로 확인할 수 있도록 나눕니다.
4. **모델 학습:** 학습 데이터에만 전처리를 맞추고 규칙을 배웁니다.
5. **평가와 활용:** 평가 데이터에서 성능을 확인하고 새 입력을 예측합니다.
''')
st.info("평가 데이터의 정보로 전처리나 모델을 미리 맞추면 ‘데이터 누수’가 생겨 실제보다 성능이 좋아 보일 수 있습니다.")
with st.expander("SVM은 어떻게 분류하나요?"):
    st.markdown('''**SVM(서포트 벡터 머신)**은 클래스를 구분하는 경계 주변의 여유 공간인 **마진**을 크게 확보하도록 학습하는 방법입니다.
경계에 영향을 주는 학습 샘플을 서포트 벡터라고 합니다. 이번 실험은 **RBF 커널**을 사용해 비선형적인 관계도 다룹니다.

측정값들의 규모를 맞추는 **표준화**와 SVM을 하나의 파이프라인으로 묶습니다. 표준화의 평균과 표준편차는 학습 데이터에서만 구합니다.''')
st.markdown('''## 예측을 책임 있게 사용하기
- **대표성:** 학습에 부족하게 포함된 집단이나 상황에서 성능이 떨어질 수 있습니다.
- **개인정보:** 필요한 데이터만 수집하고 동의와 보관 방법을 확인합니다.
- **사람의 검토:** 예측을 그대로 정답으로 받아들이지 않고 오류의 영향을 살핍니다.
- **한계:** 높은 평가 정확도가 모든 새로운 입력의 정답을 보장하지 않습니다.
''')
